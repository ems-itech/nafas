function arabic(text: string) {
  return arabicMenuText[text] ?? text;
}

export function getMenuCards(locale: "en" | "ar"): MenuCard[] {
  if (locale === "en") return menuCards;

  return menuCards.map((card) => ({
    eyebrow: arabic(card.eyebrow),
    title: arabic(card.title),
    sections: card.sections.map((section) => ({
      ...section,
      title: arabic(section.title),
      priceLabels: section.priceLabels?.map(arabic) as [string, string] | undefined,
      priceColumns: section.priceColumns?.map(arabic),
      rows: section.rows.map((row) => ({ ...row, name: arabic(row.name) })),
    })),
  }));
}
